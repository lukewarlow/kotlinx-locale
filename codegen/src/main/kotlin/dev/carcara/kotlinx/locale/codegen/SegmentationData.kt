package dev.carcara.kotlinx.locale.codegen

import java.io.File

/** These generated IDs are consumed by the rules, so the property mapping has one owner. */
private val wordClasses = listOf(
    "Other", "CR", "LF", "Newline", "Extend", "ZWJ", "Regional_Indicator", "Format",
    "Katakana", "Hebrew_Letter", "ALetter", "Single_Quote", "Double_Quote", "MidNumLet",
    "MidLetter", "MidNum", "Numeric", "ExtendNumLet", "WSegSpace",
)
private val sentenceClasses = listOf(
    "Other", "CR", "LF", "Extend", "Sep", "Format", "Sp", "Lower", "Upper", "OLetter",
    "Numeric", "ATerm", "STerm", "Close", "SContinue",
)

/** Regenerates the standalone backend and fixtures from the vendored, version-checked UCD. */
internal fun generateSegmentationData(rootDir: File) {
    val packageName = "dev.carcara.kotlinx.locale.segmentation.unicode"
    val word = propertyValues("WordBreakProperty.txt", wordClasses)
    for (i in word.indices) word[i] = word[i] * 4
    for (fields in ucdLines("emoji-data.txt")) {
        if (fields[1] == "Extended_Pictographic") {
            for (cp in rangeOf(fields[0])) word[cp] = word[cp] or 2
        }
    }
    // Classification uses the same UCD release as segmentation, not the newer
    // UnicodeData.txt that the collation generator consumes.
    for (fields in ucdLines("DerivedGeneralCategory.txt")) {
        if (fields[1].startsWith('L') || fields[1].startsWith('N')) {
            for (cp in rangeOf(fields[0])) word[cp] = word[cp] or 1
        }
    }
    val wordLikeClasses = setOf("ALetter", "Hebrew_Letter", "Numeric", "Katakana").map(wordClasses::indexOf).toSet()
    for (cp in word.indices) if (word[cp] / 4 in wordLikeClasses) word[cp] = word[cp] or 1
    val sentence = propertyValues("SentenceBreakProperty.txt", sentenceClasses)
    val source = rootDir.resolve(
        "kotlinx-locale-segmentation-unicode/src/commonMain/kotlin/" +
            packageName.replace('.', '/') + "/WordSentenceProperties.kt",
    )
    source.parentFile.mkdirs()
    source.writeText(
        buildString {
            append(LICENSE_HEADER)
            append("// GENERATED by :codegen from Unicode $UCD_VERSION. Do not edit.\n")
            append("// Regenerate with: ./gradlew :codegen:generateSegmentationData\n")
            append("package $packageName\n\n")
            append("internal const val segmentationUnicodeVersion: String = \"$UCD_VERSION\"\n\n")
            emitClasses("Wb", wordClasses)
            emitClasses("Sb", sentenceClasses)
            append("internal val wordBreakProperties: String = \"${kotlinEscape(encodeProperties(word))}\"\n")
            append("internal val sentenceBreakProperties: String = \"${kotlinEscape(encodeProperties(sentence))}\"\n")
        },
    )
    emitBoundaryFixtures(rootDir, "Word")
    emitBoundaryFixtures(rootDir, "Sentence")
}

private fun propertyValues(resource: String, classes: List<String>): IntArray {
    val values = IntArray(0x110000)
    for (fields in ucdLines(resource)) {
        val property = classes.indexOf(fields[1])
        require(property >= 0) { "Unknown property ${fields[1]} in $resource" }
        for (cp in rangeOf(fields[0])) values[cp] = property
    }
    return values
}

private fun rangeOf(field: String): IntRange = field.substringBefore("..").toInt(16)..field.substringAfter("..", field).toInt(16)

private fun encodeProperties(values: IntArray): String = buildString {
    var start = 0
    while (start < values.size) {
        val value = values[start]
        var end = start + 1
        while (end < values.size && values[end] == value) end++
        if (value != 0) {
            if (isNotEmpty()) append('\u001E')
            append(start.toString(36)).append(',').append((end - start - 1).toString(36)).append(',').append(value.toString(36))
        }
        start = end
    }
}

private fun StringBuilder.emitClasses(name: String, classes: List<String>) {
    append("internal object $name {\n")
    for ((id, property) in classes.withIndex()) append("    const val ${property.uppercase()}: Int = $id\n")
    append("}\n\n")
}

private fun emitBoundaryFixtures(rootDir: File, kind: String) {
    val resource = "${kind}BreakTest.txt"
    val raw = requireNotNull(object {}.javaClass.getResourceAsStream("/ucd/$resource")) {
        "Missing /ucd/$resource"
    }.bufferedReader().use { it.readText() }
    require(raw.startsWith("# ${kind}BreakTest-$UCD_VERSION.txt")) { "$resource is not Unicode $UCD_VERSION" }
    val cases = raw.lineSequence().map { it.substringBefore('#').trim() }.filter(String::isNotEmpty).map { line ->
        val points = ArrayList<String>()
        val boundaries = ArrayList<String>()
        for (token in line.split(Regex("\\s+"))) {
            when (token) {
                "÷" -> boundaries.add(points.size.toString(36))
                "×" -> Unit
                else -> points.add(token.toInt(16).toString(36))
            }
        }
        points.joinToString(",") + ":" + boundaries.joinToString(",")
    }.toList()
    require(cases.isNotEmpty()) { "$resource has no cases" }
    val output = rootDir.resolve(
        "kotlinx-locale-segmentation-unicode/src/commonTest/kotlin/" +
            "dev/carcara/kotlinx/locale/segmentation/conformance/${kind}BreakCaseData.kt",
    )
    output.parentFile.mkdirs()
    output.writeText(
        buildString {
            append(LICENSE_HEADER)
            append("// GENERATED by :codegen from Unicode $UCD_VERSION. Do not edit.\n")
            append("// Regenerate with: ./gradlew :codegen:generateSegmentationData\n")
            append("package dev.carcara.kotlinx.locale.segmentation.conformance\n\n")
            append("internal const val ${kind.uppercase()}_BREAK_VERSION: String = \"$UCD_VERSION\"\n\n")
            append("internal val ${kind.lowercase()}BreakCases: List<String> = listOf(\n")
            // Keep JVM constants below 64 KiB and native initializers small.
            for (chunk in cases.chunked(200)) {
                append("    \"\"\"\n")
                append(chunk.joinToString("\n"))
                append("\n\"\"\".trim(),\n")
            }
            append(").flatMap { it.lines() }\n")
        },
    )
}
