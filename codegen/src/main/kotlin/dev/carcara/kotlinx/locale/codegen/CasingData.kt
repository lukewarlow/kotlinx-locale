package dev.carcara.kotlinx.locale.codegen

import java.io.File
import java.security.MessageDigest

/** Full case mappings and contextual properties from one pinned UCD release. */
internal fun generateCasingData(rootDir: File) {
    val version = "15.1.0"
    fun resource(name: String): ByteArray = checkNotNull(
        object {}.javaClass.getResourceAsStream("/casing/$name"),
    ) { "Missing casing resource $name" }.use { it.readBytes() }
    val sums = resource("SHA256SUMS").decodeToString().lineSequence().filter { it.isNotBlank() }.associate {
        val (hash, name) = it.split("  ", limit = 2)
        name to hash
    }
    fun read(name: String): String {
        val bytes = resource(name)
        val hash = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }
        check(hash == sums[name]) { "Casing resource checksum mismatch: $name" }
        val text = bytes.decodeToString()
        if (name != "UnicodeData.txt") check(text.startsWith("# ${name.removeSuffix(".txt")}-$version.txt"))
        return text
    }
    fun rows(text: String): List<List<String>> = text.lineSequence()
        .map { it.substringBefore('#').trim() }.filter { it.isNotEmpty() }
        .map { it.split(';').map(String::trim) }.toList()
    fun sequence(value: String): String = value.split(' ').filter { it.isNotEmpty() }.joinToString(".") { it.toInt(16).toString(36) }
    val lower = sortedMapOf<Int, String>()
    val upper = sortedMapOf<Int, String>()
    val properties = IntArray(0x110000)
    for (row in rows(read("UnicodeData.txt"))) {
        val cp = row[0].toInt(16)
        properties[cp] = row[3].toInt() shl 3
        if (row[13].isNotEmpty()) lower[cp] = sequence(row[13])
        if (row[12].isNotEmpty()) upper[cp] = sequence(row[12])
    }
    for ((file, flags) in listOf(
        "DerivedCoreProperties.txt" to mapOf("Cased" to 1, "Case_Ignorable" to 2),
        "PropList.txt" to mapOf("Soft_Dotted" to 4),
    )) {
        for (row in rows(read(file))) {
            val flag = flags[row[1]] ?: continue
            val start = row[0].substringBefore("..").toInt(16)
            val end = row[0].substringAfter("..", row[0]).toInt(16)
            for (cp in start..end) properties[cp] = properties[cp] or flag
        }
    }
    val contexts = setOf("Final_Sigma", "After_Soft_Dotted", "More_Above", "After_I", "Not_Before_Dot", "Before_Dot")
    val languages = sortedSetOf<String>()
    val conditional = ArrayList<String>()
    for (row in rows(read("SpecialCasing.txt"))) {
        val cp = row[0].toInt(16)
        val conditions = row.getOrElse(4) { "" }.split(' ').filter { it.isNotEmpty() }
        if (conditions.isEmpty()) {
            lower[cp] = sequence(row[1])
            upper[cp] = sequence(row[3])
        } else {
            val language = conditions.firstOrNull { it.matches(Regex("[a-z]{2,3}")) }.orEmpty()
            if (language.isNotEmpty()) languages.add(language)
            val tests = conditions.filter { it != language }
            check(tests.all { it in contexts }) { "Unhandled casing condition: $conditions" }
            conditional.add(
                listOf(cp.toString(36), sequence(row[1]), sequence(row[3]), language, tests.joinToString(",")).joinToString(";"),
            )
        }
    }
    val ranges = ArrayList<String>()
    var start = 0
    while (start < properties.size) {
        var end = start + 1
        while (end < properties.size && properties[end] == properties[start]) end++
        if (properties[start] != 0) ranges.add(listOf(start, end - start - 1, properties[start]).joinToString(",") { it.toString(36) })
        start = end
    }
    fun encode(mapping: Map<Int, String>): String = mapping.entries.joinToString(";") { (cp, value) -> "${cp.toString(36)}:$value" }
    val output = rootDir.resolve(
        "kotlinx-locale-casing-unicode/src/commonMain/kotlin/dev/carcara/kotlinx/locale/casing/unicode/CasingData.kt",
    )
    output.parentFile.mkdirs()
    output.writeText(
        buildString {
            append(LICENSE_HEADER)
            append("// GENERATED by :codegen:generateCasingData from Unicode $version. Do not edit.\n")
            append("package dev.carcara.kotlinx.locale.casing.unicode\n\n")
            for ((name, value) in listOf(
                "casingDataVersion" to version,
                "casingLanguages" to languages.joinToString(" "),
                "lowercaseMappings" to encode(lower),
                "uppercaseMappings" to encode(upper),
                "casingProperties" to ranges.joinToString(";"),
                "conditionalMappings" to conditional.joinToString("|"),
            )) {
                append("internal const val $name: String = \"${kotlinEscape(value)}\"\n")
            }
        },
    )
}
